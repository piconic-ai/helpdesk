const permissionLabels: Record<Permission, string> = {
  read_body: '問い合わせ本文の閲覧',
  send: 'メール送信',
  external_fetch: '外部サービスへの接続',
}
export function permissionText(permissions: Permission[]) {
  return (
    permissions.map((p) => permissionLabels[p]).join('、') ||
    '追加の権限はありません'
  )
}

